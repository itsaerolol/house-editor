import sys, subprocess, json, base64, io
subprocess.run(['/home/claude/farmhouse-editor/scripts/ensure_vite.sh'])
from playwright.sync_api import sync_playwright
from PIL import Image
ids = json.loads(open('/tmp/ids.json').read())
C, N = 220, 12
out = {}
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'])
    for k in range(0, len(ids), N):
        batch = ids[k:k + N]
        cols = 4
        rows = (len(batch) + cols - 1) // cols
        pg = b.new_page(viewport={'width': cols * (C + 4) + 8, 'height': rows * (C + 4) + 8})
        pg.add_style_tag if False else None
        pg.goto(f"http://127.0.0.1:5199/preview.html?thumb=1&q=2&items={','.join(batch)}&view=hero&cols={cols}&cw={C}&ch={C}&zoom=1.15")
        pg.add_style_tag(content='html,body,.cell{background:transparent!important}')
        try: pg.wait_for_function('window.__ready === true', timeout=120000)
        except Exception as e: print('timeout', batch[0])
        pg.wait_for_timeout(400)
        png = pg.screenshot(omit_background=True, timeout=120000)
        im = Image.open(io.BytesIO(png)).convert('RGBA')
        boxes = pg.evaluate("[...document.querySelectorAll('.cell')].map(e=>{const r=e.getBoundingClientRect();return [r.x,r.y,r.width,r.height]})")
        for cid, (x, y, w, h) in zip(batch, boxes):
            t = im.crop((int(x), int(y), int(x + w), int(y + h))).resize((160, 160), Image.LANCZOS)
            t.save(f'/tmp/thumbs/{cid}.webp', 'WEBP', quality=80, method=6)
            buf = io.BytesIO(); t.save(buf, 'WEBP', quality=80, method=6)
            out[cid] = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
        pg.close()
        print('batch', k, flush=True)
    b.close()
with open('src/ui/thumbs.ts', 'w') as f:
    f.write('// Generated by scripts/thumbs.py: studio renders of every catalog item for the hotbar.\nexport const THUMBS: Record<string, string> = ' + json.dumps(out, indent=0) + ';\n')
print('done', len(out))
