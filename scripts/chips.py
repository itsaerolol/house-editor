import json, subprocess
subprocess.run(['/home/claude/farmhouse-editor/scripts/ensure_vite.sh'])
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    pg = b.new_page()
    pg.goto('http://127.0.0.1:5199/preview.html?chips=1')
    pg.wait_for_function('window.__chips', timeout=180000)
    chips = pg.evaluate('window.__chips')
    b.close()
with open('src/ui/swatches.ts', 'w') as f:
    f.write('// Generated by scripts/chips.py: a sample chip for every material (real texture tile, tinted, with sheen).\nexport const SWATCHES: Record<string, string> = ' + json.dumps(chips, indent=0) + ';\n')
print(len(chips), sum(len(v) for v in chips.values()) // 1024, 'KB')
